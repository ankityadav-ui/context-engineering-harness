class MaskingRejectedError(RuntimeError):
    """Raised when masked content did not pass the safety validation.

    The upload fails closed: nothing is embedded or indexed, and the
    error message never contains the original text.
    """


# Find the backend directory.
BASE_DIR = Path(__file__).resolve().parents[2]


# Define the original document storage directory.
DOCUMENT_STORAGE_DIR = (
    BASE_DIR / "storage" / "documents"
)


# Define the extracted image storage directory.
IMAGE_STORAGE_DIR = (
    BASE_DIR / "storage" / "images"
)


# Documents are stored under an id generated by this application, so the
# id can be validated before it is ever turned into a path.
DOCUMENT_ID_PATTERN = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def validate_document_id(document_id: str) -> str:
    """Return a safe document id or raise ValueError."""

    if (
        not isinstance(document_id, str)
        or not DOCUMENT_ID_PATTERN.match(document_id.strip())
    ):
        raise ValueError(
            "document_id must contain only letters, numbers, "
            "hyphens, and underscores."
        )

    return document_id.strip()


def resolve_stored_document_path(document_id: str) -> Path:
    """Return the stored PDF path for a document id."""

    return (
        DOCUMENT_STORAGE_DIR
        / f"{validate_document_id(document_id)}.pdf"
    )


def resolve_stored_image_dir(document_id: str) -> Path:
    """Return the extracted-image directory for a document id."""

    return IMAGE_STORAGE_DIR / validate_document_id(document_id)


# Masked uploads never keep the raw PDF. The sanitized text is kept so
# the Context Engine's full-text fallback can still ground a summary
# without re-reading (and re-sending) the original document.
MASKED_TEXT_SUFFIX = ".masked.txt"


def resolve_stored_masked_text_path(document_id: str) -> Path:
    """Return the sanitized full-text artifact path for a document id."""

    return DOCUMENT_STORAGE_DIR / (
        validate_document_id(document_id) + MASKED_TEXT_SUFFIX
    )


def build_full_text(content_units: list[dict]) -> str:
    """Join the searchable text of text and table units."""

    return "\n\n".join(
        unit.get("content", "") or ""
        for unit in content_units
        if unit.get("content_type") in {"text", "table"}
        and str(unit.get("content", "")).strip()
    )


def write_masked_text_artifact(
    document_id: str,
    content_units: list[dict],
) -> Path | None:
    """Store the masked full text so the fallback never reads raw PII.

    Only safety-validated masked content is passed here. Returns None
    when there is no text to store.
    """

    text = build_full_text(content_units)

    if not text.strip():
        return None

    path = resolve_stored_masked_text_path(document_id)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")

    return path


def read_masked_text_artifact(document_id: str) -> str | None:
    """Return the stored masked full text, or None when absent."""

    try:
        path = resolve_stored_masked_text_path(document_id)
    except ValueError:
        return None

    if not path.is_file():
        return None

    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None

    return text if text.strip() else None


def document_storage_status(document_id: str) -> dict:
    """Report which local artifacts exist for one document."""

    return {
        "pdf_stored": resolve_stored_document_path(
            document_id
        ).is_file(),
        "images_stored": resolve_stored_image_dir(
            document_id
        ).is_dir(),
        "masked_text_stored": resolve_stored_masked_text_path(
            document_id
        ).is_file(),
    }


def _display_path(path: Path) -> str:
    """Describe a removed path relative to the backend directory."""

    try:
        return str(path.relative_to(BASE_DIR))

    except ValueError:
        # Storage was pointed somewhere outside the backend directory.
        return str(path)


def delete_stored_document_files(document_id: str) -> list[str]:
    """
    Remove the stored PDF and extracted images for one document.

    The id is validated before any path is built, so a crafted id cannot
    escape the document or image storage directories.
    """

    removed: list[str] = []

    pdf_path = resolve_stored_document_path(document_id)

    if pdf_path.is_file():
        pdf_path.unlink()
        removed.append(_display_path(pdf_path))

    masked_text_path = resolve_stored_masked_text_path(document_id)

    if masked_text_path.is_file():
        masked_text_path.unlink()
        removed.append(_display_path(masked_text_path))

    image_dir = resolve_stored_image_dir(document_id)

    if image_dir.is_dir():
        shutil.rmtree(image_dir)
        removed.append(_display_path(image_dir) + "/")

    return removed


def save_document(
    file: UploadFile,
) -> tuple[str, str, Path]:
    # Make sure the storage directory exists.
    DOCUMENT_STORAGE_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Get the original filename.
    original_filename = file.filename or "unknown.pdf"

    # Extract the extension.
    extension = Path(
        original_filename
    ).suffix.lower()

    # Only accept PDFs.
    if extension != ".pdf":
        raise ValueError(
            "Only PDF documents are supported."
        )

    # Generate a unique document ID.
    document_id = str(uuid4())

    # Use the generated ID as the stored filename.
    stored_filename = f"{document_id}.pdf"

    # Create the final storage path.
    destination = (
        DOCUMENT_STORAGE_DIR / stored_filename
    )

    # Save the uploaded PDF.
    with destination.open("wb") as buffer:
        shutil.copyfileobj(
            file.file,
            buffer,
        )

    # Return document information.
    return (
        document_id,
        original_filename,
        destination,
    )


# Replace the content of text and table units with masked content
# before embedding. Runs AFTER extraction (including OCR), so scanned
# pages are masked too. Image units are skipped: image pixels cannot
# be masked by this pipeline.
def mask_content_units(
    content_units: list[dict],
    document_id: str,
) -> dict:
    masked_entities = 0

    # One registry for the whole document: the same value receives the
    # same placeholder in every chunk, so masked chunks stay consistent
    # with each other and cannot be correlated by numbering.
    registry = PlaceholderRegistry()

    # The document header (the first text unit's leading line) is where
    # the person's name usually sits; the header rule is enabled only
    # there so body headings are never treated as names.
    header_pending = True

    for unit in content_units:
        if unit.get("content_type") == "image":
            continue

        content = unit.get("content", "")

        if not content.strip():
            continue

        include_header_name = (
            header_pending and unit.get("content_type") == "text"
        )

        pipeline_output = mask_and_validate(
            text=content,
            document_id=document_id,
            registry=registry,
            include_header_name=include_header_name,
        )

        if include_header_name:
            header_pending = False

        result = pipeline_output["result"]
        safety = pipeline_output["safety"]

        if not safety["passed"]:
            # Fail closed. The message reports the failed check only;
            # it never includes the original text or raw entities.
            raise MaskingRejectedError(
                "Masked content did not pass the safety validation "
                "(reasons: "
                + "; ".join(safety.get("reasons", []))
                + "). Nothing was embedded or indexed."
            )

        unit["content"] = result.masked_text
        masked_entities += len(result.entities)

    return {
        "applied": True,
        "safety_passed": True,
        "masked_entities": masked_entities,
    }

# Run the OCR fallback for pages the extractor could not read.
def run_pdf_text_pipeline(
    document_path: Path,
    document_id: str,
) -> tuple[list[dict], list[dict], list[dict]]:
    # Extract selectable text and the pages that need OCR.
    text_units, pages_needing_ocr = extract_text_from_pdf(
        document_path=document_path,
        document_id=document_id,
    )

    # Run Tesseract OCR on the pages the extractor could not read.
    # A valid PDF is never empty here: every page is either retrievable
    # text or content for the OCR fallback.
    if pages_needing_ocr:
        ocr_units = extract_text_with_ocr(
            document_path=document_path,
            document_id=document_id,
            pages=pages_needing_ocr,
        )

        text_units.extend(ocr_units)

    return text_units, pages_needing_ocr, []


# Process a PDF through extraction, chunking, embedding, and indexing.

def process_document(
    document_path: Path,
    document_id: str,
    apply_masking: bool = False,
) -> tuple[list[dict], list[int], list[dict], list[dict], dict]:
    # Extract selectable text, run OCR on pages that could not be
    # parsed, and return a single collection of readable units. This is
    # the entry point every caller uses so a scanned page is never
    # silently empty.
    text_units, pages_needing_ocr, _ = run_pdf_text_pipeline(
        document_path=document_path,
        document_id=document_id,
    )

    # Extract structured tables from the PDF.
    table_units = extract_tables_from_pdf(
        document_path=document_path,
        document_id=document_id,
    )

    # Extract embedded images from the PDF. When masking is requested,
    # images are NOT extracted: image pixels cannot be sanitized by the
    # masking pipeline, so they must not be stored or indexed.
    if apply_masking:
        image_units = []
    else:
        image_units = extract_images_from_pdf(
            document_path=document_path,
            document_id=document_id,
            image_storage_dir=IMAGE_STORAGE_DIR,
        )

    # Convert text, tables, and images into unified content units.
    content_units = build_content_units(
        text_units=text_units,
        table_units=table_units,
        image_units=image_units,
    )

    # When masking is requested, sanitize every text-bearing unit
    # BEFORE embedding or indexing. If the safety validation fails the
    # pipeline raises and nothing reaches the vector index.
    masking_stats: dict = {
        "applied": False,
        "safety_passed": None,
        "masked_entities": 0,
    }

    if apply_masking:
        masking_stats = mask_content_units(
            content_units=content_units,
            document_id=document_id,
        )

    # Generate embeddings for all content units (masked content when
    # masking was requested).
    embedded_units = embed_content_units(
        content_units
    )

    # Store the generated vectors and metadata in Pinecone.
    upsert_content_units(
        embedded_units
    )

    # Return the processed content and extraction statistics.
    return (
        content_units,
        pages_needing_ocr,
        table_units,
        image_units,
        masking_stats,
    )