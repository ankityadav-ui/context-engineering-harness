# Import BaseModel for defining the structure of our API data.
from pydantic import BaseModel

# Import Field so that we can add validation rules
# to fields inside our request model.
from pydantic import Field


# ---------------------------------------------------------
# Chat Request
# ---------------------------------------------------------
#
# This defines the data that the frontend must send
# when calling POST /chat.
#
class ChatRequest(BaseModel):

    # The user must provide a message.
    #
    # min_length prevents completely empty messages.
    message: str = Field(
        min_length=1,
        description="Message sent by the user",
    )


# ---------------------------------------------------------
# Chat Response
# ---------------------------------------------------------
#
# This defines the structure of the response
# returned by our backend.
#
class ChatResponse(BaseModel):

    # Text generated by the LLM.
    response: str


# This schema defines the response returned after a document is uploaded.

class DocumentUploadResponse(BaseModel):
    # Unique internal ID assigned to the uploaded document.
    document_id: str

    # Original filename supplied by the user.
    filename: str

    # Current processing status.
    status: str


# Schema returned after document processing.
class DocumentUploadResponse(BaseModel):
    # Unique document identifier.
    document_id: str

    # Original filename.
    filename: str

    # Processing status.
    status: str

    # Number of extracted text units.
    text_units: int

    # Number of pages processed with OCR.
    ocr_pages: int

    # Number of detected tables.
    tables: int

    # Number of extracted images.
    images: int

# Request schema used for semantic document search.
class DocumentSearchRequest(BaseModel):

    # The question or search query entered by the user.
    query: str = Field(min_length=1)

    # Optional document ID used to restrict the search.
    document_id: str | None = None

    # Number of relevant results to return.
    top_k: int = Field(
        default=5,
        ge=1,
        le=20,
    )

# Request schema used for asking questions against indexed documents.
class RAGRequest(BaseModel):

    # The user's question.
    query: str = Field(min_length=1)

    # Optional document ID used to restrict retrieval.
    document_id: str | None = None

    # Number of relevant chunks to retrieve.
    top_k: int = Field(
        default=5,
        ge=1,
        le=20,
    )