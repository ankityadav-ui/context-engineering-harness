"""Context preview data tests against the authoritative assembly path.

External services are mocked; conversations and memories use the
in-memory SQLite database from the shared fixtures. The tests verify the
actual response contract the Context Inspector renders.
"""

import app.context_engine.engine as engine
import app.main as main_module
from app.context_engine import conversation_service


def _seed_messages(session_factory, conversation_id, count):
    with session_factory() as db:
        for number in range(1, count + 1):
            conversation_service.save_message(
                db=db,
                conversation_id=conversation_id,
                role="user" if number % 2 else "assistant",
                content=f"turn-{number}",
            )


def _rag_result():
    return {
        "content_type": "text",
        "content": "The return window is 30 days.",
        "document_id": "doc-1",
        "page_number": 2,
        "score": 0.87,
    }


def _graph_relationship():
    return {
        "matched_entity": "Acme",
        "source": "Acme",
        "relationship": "RELATES_TO",
        "target": "Policy",
        "direction": "outgoing",
    }


def test_context_preview_returns_conversation_memory_rag_and_graph(
    api_client,
    sqlite_session_factory,
    isolated_assembly,
    monkeypatch,
):
    created = api_client.post("/conversations", json={}).json()
    _seed_messages(sqlite_session_factory, created["id"], 8)

    memory = api_client.post(
        "/memory",
        json={
            "user_id": "user-1",
            "memory_type": "preference",
            "content": "Prefers concise answers about returns.",
            "importance": 5,
        },
    )

    assert memory.status_code == 201

    monkeypatch.setattr(
        engine,
        "retrieve_context",
        lambda **_kwargs: [_rag_result()],
    )
    monkeypatch.setattr(
        engine,
        "_get_graph_context",
        lambda _query: [_graph_relationship()],
    )

    response = api_client.post(
        "/context/preview",
        json={
            "query": "What is the return policy?",
            "top_k": 3,
            "conversation_id": created["id"],
            "user_id": "user-1",
        },
    )

    assert response.status_code == 200

    body = response.json()
    sources = body["sources"]

    # No answer is generated by a preview.
    assert "answer" not in body

    # Older messages are summarized; the latest six stay as messages.
    conversation = sources["conversation"]

    assert conversation["total_messages"] == 8
    assert conversation["older_count"] == 2
    assert conversation["recent_count"] == 6
    assert conversation["summary"] == "Older messages summarized."
    assert [item["content"] for item in conversation["recent_messages"]] == [
        f"turn-{number}" for number in range(3, 9)
    ]

    # Real long-term memory retrieval from the in-memory database.
    assert len(sources["memory"]) == 1
    assert sources["memory"][0]["memory_type"] == "preference"
    assert sources["memory"][0]["content"] == (
        "Prefers concise answers about returns."
    )
    assert "score" in sources["memory"][0]

    # Document evidence keeps its source metadata for the inspector.
    assert sources["rag"] == [_rag_result()]

    # Graph relationships keep the matched entity and endpoints.
    assert sources["knowledge_graph"] == [_graph_relationship()]

    assert body["source_errors"] == []
    assert body["system_prompt"]["using_default"] is True
    assert body["model"]["model"] == main_module.describe_active_provider()[
        "model"
    ]

    formatted = body["formatted_context"]

    assert "CONVERSATION SUMMARY:" in formatted
    assert "Older messages summarized." in formatted
    assert "turn-8" in formatted
    assert "RELEVANT DOCUMENT EVIDENCE:" in formatted
    assert "document_id=doc-1" in formatted
    assert "The return window is 30 days." in formatted
    assert "RELEVANT LONG-TERM MEMORIES:" in formatted
    assert "Prefers concise answers about returns." in formatted
    assert "KNOWLEDGE GRAPH RELATIONSHIPS:" in formatted
    assert "Acme --RELATES_TO--> Policy" in formatted


def test_context_preview_custom_prompt_state_is_reported(
    api_client,
    sqlite_session_factory,
    isolated_assembly,
):
    created = api_client.post("/conversations", json={}).json()

    saved = api_client.put(
        f"/conversations/{created['id']}/system-prompt",
        json={"custom_prompt": "Answer in bullet points."},
    )

    assert saved.status_code == 200

    response = api_client.post(
        "/context/preview",
        json={
            "query": "Anything",
            "conversation_id": created["id"],
        },
    )

    assert response.status_code == 200
    assert response.json()["system_prompt"]["using_default"] is False


def test_context_preview_distinguishes_rag_error_from_empty_rag(
    api_client,
    isolated_assembly,
    monkeypatch,
):
    def failing_retrieval(**_kwargs):
        raise RuntimeError("vector store unavailable")

    monkeypatch.setattr(engine, "retrieve_context", failing_retrieval)

    response = api_client.post(
        "/context/preview",
        json={"query": "What is the policy?"},
    )

    assert response.status_code == 200

    body = response.json()

    # A failed source is empty AND explicitly reported as an error.
    assert body["sources"]["rag"] == []
    assert body["source_errors"] == [
        {"source": "rag", "error": "vector store unavailable"}
    ]

    # The preview still contains the question, not fabricated evidence.
    assert "What is the policy?" in body["formatted_context"]


def test_context_preview_distinguishes_conversation_error_from_empty(
    api_client,
    isolated_assembly,
    monkeypatch,
):
    created = api_client.post("/conversations", json={}).json()

    def failing_conversation_context(**_kwargs):
        raise RuntimeError("conversation storage unavailable")

    monkeypatch.setattr(
        engine,
        "_get_conversation_context",
        failing_conversation_context,
    )

    response = api_client.post(
        "/context/preview",
        json={
            "query": "Anything",
            "conversation_id": created["id"],
        },
    )

    assert response.status_code == 200

    body = response.json()

    assert body["sources"]["conversation"] is None
    assert body["source_errors"] == [
        {
            "source": "conversation",
            "error": "conversation storage unavailable",
        }
    ]


def test_context_preview_does_not_generate_a_chat_answer(
    api_client,
    sqlite_session_factory,
    isolated_assembly,
    monkeypatch,
):
    created = api_client.post("/conversations", json={}).json()

    # Two messages are inside the recent window, so no summary (and no
    # summarizer LLM call) is needed for the preview either.
    _seed_messages(sqlite_session_factory, created["id"], 2)

    def fail_if_called(*_args, **_kwargs):
        raise AssertionError("Preview must not generate an answer.")

    monkeypatch.setattr(main_module, "generate_response", fail_if_called)
    monkeypatch.setattr(
        main_module,
        "generate_multimodal_response",
        fail_if_called,
    )

    response = api_client.post(
        "/context/preview",
        json={
            "query": "What did we discuss?",
            "conversation_id": created["id"],
        },
    )

    assert response.status_code == 200
    assert "answer" not in response.json()
